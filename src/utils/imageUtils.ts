// Generates a simple hash from a string
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = str.charCodeAt(i) + ((hash << 5) - hash);
  }
  return Math.abs(hash);
}

export function getDeterministicImageForRecipe(title: string): string {
  const lowerTitle = title.toLowerCase();
  
  // Find a matching category based on the title keywords
  const categories = Object.keys(fallbackImages) as Array<keyof typeof fallbackImages>;
  let matchedCategory: keyof typeof fallbackImages = 'generic';
  
  for (const category of categories) {
    if (category !== 'generic' && lowerTitle.includes(category)) {
      matchedCategory = category;
      break;
    }
  }

  // Pick an image deterministically from the matched category
  const images = fallbackImages[matchedCategory];
  const hash = hashString(title);
  const index = hash % images.length;
  
  return images[index];
}
